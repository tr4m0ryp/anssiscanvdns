#!/bin/sh
# Wire the public side into the existing Caddy: the DoH endpoint, the CA
# download, the password-protected editor, and TLS for the proxied hosts.
# The editor password is generated once and printed; keep it somewhere safe.
set -eu
HERE="$(cd "$(dirname "$0")" && pwd)"
ROOT="$(cd "$HERE/../.." && pwd)"
. "$HERE/env.sh"

install -d -m 755 "$ETC/public"
install -m 644 "$ETC/ca.crt" "$ETC/public/ca.crt"
if [ ! -f "$ETC/admin.hash" ]; then
  PW="$(openssl rand -base64 18 | tr -d '/+=' | cut -c1-20)"
  caddy hash-password --plaintext "$PW" > "$ETC/admin.hash"
  chmod 600 "$ETC/admin.hash"
  echo "ADMIN_PASSWORD (user anssis): $PW"
fi
SITES="$(python3 -c 'import json,sys; print(", ".join(f"{h}, *.{h}" for h in json.load(open(sys.argv[1]))["hosts"]))' "$ROOT/rules/http.json")"

NEW=/etc/caddy/anssis.caddy.new
cat > "$NEW" <<CADDY
# Generated by deploy/server/caddy.sh
$PUBLIC_HOST {
	handle /dns-query {
		reverse_proxy 127.0.0.1:$DOH_PORT
	}
	handle /ca.crt {
		root * $ETC/public
		header Content-Type application/x-x509-ca-cert
		file_server
	}
	handle {
		basic_auth {
			anssis $(cat "$ETC/admin.hash")
		}
		reverse_proxy 127.0.0.1:$ADMIN_PORT
	}
}

$SITES {
	tls $ETC/tls/proxy.crt $ETC/tls/proxy.key
	reverse_proxy 127.0.0.1:$MITM_PORT {
		flush_interval -1
	}
}
CADDY
if cmp -s "$NEW" /etc/caddy/anssis.caddy; then rm -f "$NEW"; exit 0; fi
mv "$NEW" /etc/caddy/anssis.caddy
grep -q '^import /etc/caddy/anssis.caddy' /etc/caddy/Caddyfile || printf '\nimport /etc/caddy/anssis.caddy\n' >> /etc/caddy/Caddyfile
caddy validate --config /etc/caddy/Caddyfile --adapter caddyfile >/dev/null 2>&1 || { echo "caddy config invalid"; caddy validate --config /etc/caddy/Caddyfile --adapter caddyfile; exit 1; }
systemctl reload caddy
