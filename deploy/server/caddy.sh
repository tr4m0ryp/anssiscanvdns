#!/bin/sh
# Wire the public side into the existing Caddy: the DoH endpoint, the CA
# download, the password-protected editor, and TLS for the proxied hosts.
# The editor password is generated once and printed; keep it somewhere safe.
# Both sites write a JSON access log (client IP, User-Agent, host, path; Caddy
# redacts cookies) that the editor's Devices table reads.
set -eu
HERE="$(cd "$(dirname "$0")" && pwd)"
ROOT="$(cd "$HERE/../.." && pwd)"
. "$HERE/env.sh"

install -d -m 755 "$ETC/public"
install -m 644 "$ETC/ca.crt" "$ETC/public/ca.crt"
install -m 644 "$ROOT/deploy/windows/setup.ps1" "$ETC/public/win"
install -m 644 "$ROOT/deploy/windows/undo.ps1" "$ETC/public/win-undo"
if [ ! -f "$ETC/admin.hash" ]; then
  PW="$(openssl rand -base64 18 | tr -d '/+=' | cut -c1-20)"
  caddy hash-password --plaintext "$PW" > "$ETC/admin.hash"
  chmod 600 "$ETC/admin.hash"
  echo "ADMIN_PASSWORD (user anssis): $PW"
fi
SITES="$(python3 -c 'import json,sys; print(", ".join(f"{h}, *.{h}" for h in json.load(open(sys.argv[1]))["hosts"]))' "$ROOT/rules/http.json")"

NEW=/etc/caddy/anssis.caddy.new
cat > "$NEW" <<CADDY
# Generated by deploy/server/caddy.sh
$PUBLIC_HOST${PUBLIC_ALIASES:+, $PUBLIC_ALIASES} {
	log {
		output file /var/log/caddy/anssis-access.log {
			mode 0644
			roll_size 20MiB
			roll_keep 5
		}
		format json
	}
	handle /dns-query {
		reverse_proxy 127.0.0.1:$DOH_PORT
	}
	handle /ca.crt {
		root * $ETC/public
		header Content-Type application/x-x509-ca-cert
		file_server
	}
	@win path /win /win-undo
	handle @win {
		root * $ETC/public
		header Content-Type "text/plain; charset=utf-8"
		file_server
	}
	handle {
		basic_auth {
			anssis $(cat "$ETC/admin.hash")
		}
		reverse_proxy 127.0.0.1:$ADMIN_PORT
	}
}

$SITES {
	tls $ETC/tls/proxy.crt $ETC/tls/proxy.key
	log {
		output file /var/log/caddy/anssis-access.log {
			mode 0644
			roll_size 20MiB
			roll_keep 5
		}
		format json
	}
	reverse_proxy 127.0.0.1:$MITM_PORT {
		flush_interval -1
	}
}
CADDY
if cmp -s "$NEW" /etc/caddy/anssis.caddy; then rm -f "$NEW"; exit 0; fi
[ -f /etc/caddy/anssis.caddy ] && cp /etc/caddy/anssis.caddy /etc/caddy/anssis.caddy.prev
mv "$NEW" /etc/caddy/anssis.caddy
grep -q '^import /etc/caddy/anssis.caddy' /etc/caddy/Caddyfile || printf '\nimport /etc/caddy/anssis.caddy\n' >> /etc/caddy/Caddyfile
if ! caddy validate --config /etc/caddy/Caddyfile --adapter caddyfile >/dev/null 2>&1; then
  echo "anssis: generated Caddy config invalid, restoring the previous one" >&2
  if [ -f /etc/caddy/anssis.caddy.prev ]; then mv /etc/caddy/anssis.caddy.prev /etc/caddy/anssis.caddy; else rm -f /etc/caddy/anssis.caddy; fi
  exit 1
fi
systemctl reload caddy
