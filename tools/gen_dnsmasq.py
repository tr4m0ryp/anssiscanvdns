#!/usr/bin/env python3
"""Render rules/dns.txt and the hosts in rules/http.json into dnsmasq lines.

Usage: gen_dnsmasq.py <repo-root> <proxy-ip>  (prints the config to stdout)

Every proxied host resolves to the proxy for A queries. Its AAAA queries get
an empty answer, so a dual-stack client can never reach the real site over
IPv6 and slip past the proxy.
"""

import json
import re
import sys
from pathlib import Path

DOMAIN = re.compile(r"^(?=.{1,253}$)([a-z0-9-]{1,63}\.)*[a-z0-9-]{1,63}$")
IPV4 = re.compile(r"^(\d{1,3}\.){3}\d{1,3}$")


def domain(s: str, where: str) -> str:
    s = s.strip().lower().rstrip(".")
    if not DOMAIN.match(s):
        raise SystemExit(f"{where}: invalid domain {s!r}")
    return s


def render(root: Path, proxy_ip: str) -> str:
    out = ["# Generated by tools/gen_dnsmasq.py; edit rules/ instead."]
    hosts = json.loads((root / "rules/http.json").read_text())["hosts"]
    for h in hosts:
        d = domain(h, "http.json")
        out += [f"address=/{d}/{proxy_ip}", f"address=/{d}/::"]
    for n, raw in enumerate((root / "rules/dns.txt").read_text().splitlines(), 1):
        line = raw.split("#", 1)[0].split()
        if not line:
            continue
        where = f"dns.txt:{n}"
        if line[0] == "block" and len(line) == 2:
            out.append(f"address=/{domain(line[1], where)}/")
        elif line[0] == "point" and len(line) == 3 and IPV4.match(line[2]):
            d = domain(line[1], where)
            out += [f"address=/{d}/{line[2]}", f"address=/{d}/::"]
        else:
            raise SystemExit(f"{where}: cannot parse {raw.strip()!r}")
    return "\n".join(out) + "\n"


if __name__ == "__main__":
    if len(sys.argv) != 3:
        raise SystemExit(__doc__)
    sys.stdout.write(render(Path(sys.argv[1]), sys.argv[2]))
